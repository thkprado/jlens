//! `cargo xtask homebrew`: the Homebrew formula of the command line, for the tap
//! `thkprado/homebrew-jlens`.
//!
//! The formula installs the release binaries of macOS and Linux, never builds them: each URL
//! and checksum comes from the `SHA256SUMS` of the release.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::wasm::workspace_version;

/// The release targets (binaries.yml) the formula installs, by Homebrew's `on_<os>` and
/// `on_<cpu>` blocks.
const TARGETS: [(&str, &str, &str); 4] = [
    ("macos", "arm", "aarch64-apple-darwin"),
    ("macos", "intel", "x86_64-apple-darwin"),
    ("linux", "arm", "aarch64-unknown-linux-musl"),
    ("linux", "intel", "x86_64-unknown-linux-musl"),
];

/// Prints the formula of the workspace version, with the archives and checksums listed in
/// `sums` (a `SHA256SUMS` file), downloaded from `base`: by default the GitHub release of the
/// version, or another directory (a `file://` URL, for CI) holding the archives.
pub fn print(sums: &Path, base: Option<&str>) -> Result<()> {
    let version = workspace_version()?;
    let text = fs::read_to_string(sums).with_context(|| format!("reading {}", sums.display()))?;
    let base = base.map_or_else(
        || format!("https://github.com/thkprado/jlens/releases/download/v{version}"),
        |b| b.trim_end_matches('/').to_owned(),
    );
    print!("{}", formula(&version, &text, &base)?);
    Ok(())
}

fn formula(version: &str, sums: &str, base: &str) -> Result<String> {
    let archives = TARGETS
        .iter()
        .map(|(os, cpu, target)| Ok((*os, *cpu, archive(sums, target, "tar.gz")?)))
        .collect::<Result<Vec<_>>>()?;
    // Homebrew reads the version from release URLs (`brew audit --strict` rejects a redundant
    // `version`); CI archives are named after the commit, so they need it.
    let named = archives
        .iter()
        .all(|(_, _, (_, file))| file.starts_with(&format!("jlens-{version}-")));
    let version_line = if named {
        String::new()
    } else {
        format!("  version \"{version}\"\n")
    };
    let mut out = format!(
        r#"# Generated by `cargo xtask homebrew` in thkprado/jlens, from the SHA256SUMS of the release.
# Do not edit: the Homebrew workflow of thkprado/jlens replaces it when a release is published.
class Jlens < Formula
  desc "Evaluate, check and explain JSONata expressions"
  homepage "https://thkprado.github.io/jlens/"
{version_line}  license "MIT"
"#
    );
    for os in ["macos", "linux"] {
        out.push_str(&format!("\n  on_{os} do\n"));
        for (_, cpu, (sha256, file)) in archives.iter().filter(|a| a.0 == os) {
            out.push_str(&format!(
                "    on_{cpu} do\n      url \"{base}/{file}\"\n      sha256 \"{sha256}\"\n    end\n"
            ));
        }
        out.push_str("  end\n");
    }
    out.push_str(
        r##"
  def install
    bin.install "jlens"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/jlens --version")
    assert_equal "3", pipe_output("#{bin}/jlens eval '$sum(a)'", '{"a": [1, 2]}').chomp
  end
end
"##,
    );
    Ok(out)
}

/// The checksum and the file name of the archive of `target` (extension `ext`) in a `SHA256SUMS`
/// file (`<sha256>  <file>`, or `<sha256> *<file>` from a binary-mode checksum).
pub fn archive<'a>(sums: &'a str, target: &str, ext: &str) -> Result<(&'a str, &'a str)> {
    let suffix = format!("-{target}.{ext}");
    sums.lines()
        .filter_map(|line| line.split_once(' '))
        .map(|(sha256, file)| (sha256, file.trim_start_matches([' ', '*'])))
        .find(|(_, file)| file.starts_with("jlens-") && file.ends_with(&suffix))
        .filter(|(sha256, _)| sha256.len() == 64 && sha256.bytes().all(|b| b.is_ascii_hexdigit()))
        .with_context(|| format!("no checksum of a jlens-*{suffix} archive in SHA256SUMS"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sums() -> String {
        TARGETS
            .iter()
            .map(|(_, _, target)| target)
            .chain(&["x86_64-pc-windows-msvc"])
            .enumerate()
            .map(|(i, target)| {
                let ext = if target.contains("windows") {
                    "zip"
                } else {
                    "tar.gz"
                };
                format!(
                    "{}  jlens-0.14.0-{target}.{ext}\n",
                    i.to_string().repeat(64)
                )
            })
            .collect()
    }

    #[test]
    fn picks_each_archive_by_os_and_cpu() {
        let formula = formula("0.14.0", &sums(), "https://example.com/v0.14.0").unwrap();
        let macos = formula.split("  on_linux do").next().unwrap();
        assert!(macos.contains(&format!(
            "    on_arm do\n      \
             url \"https://example.com/v0.14.0/jlens-0.14.0-aarch64-apple-darwin.tar.gz\"\n      \
             sha256 \"{}\"\n    end\n",
            "0".repeat(64)
        )));
        let linux = formula.split("  on_linux do").nth(1).unwrap();
        assert!(linux.contains(&format!(
            "    on_intel do\n      \
             url \"https://example.com/v0.14.0/jlens-0.14.0-x86_64-unknown-linux-musl.tar.gz\"\n      \
             sha256 \"{}\"\n    end\n",
            "3".repeat(64)
        )));
        assert!(!formula.contains("  version "));
        assert!(!formula.contains("windows"));
    }

    #[test]
    fn states_the_version_of_archives_named_after_a_commit() {
        let sums = sums().replace("jlens-0.14.0-", "jlens-abc123-");
        let formula = formula("0.14.0", &sums, "file:///tmp/jlens-dist").unwrap();
        assert!(formula.contains("  version \"0.14.0\"\n  license \"MIT\"\n"));
    }

    #[test]
    fn reads_binary_mode_lines_and_rejects_a_missing_archive() {
        let sums = format!(
            "{}  *jlens-abc-aarch64-apple-darwin.tar.gz\n",
            "f".repeat(64)
        );
        assert_eq!(
            archive(&sums, "aarch64-apple-darwin", "tar.gz").unwrap().1,
            "jlens-abc-aarch64-apple-darwin.tar.gz"
        );
        assert!(archive(&sums, "x86_64-apple-darwin", "tar.gz").is_err());
        assert!(
            archive(
                "abc  jlens-1-aarch64-apple-darwin.tar.gz",
                "aarch64-apple-darwin",
                "tar.gz"
            )
            .is_err()
        );
    }
}
