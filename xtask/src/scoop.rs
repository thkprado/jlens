//! `cargo xtask scoop`: the Scoop manifest of the command line, for the bucket
//! `thkprado/scoop-jlens`.
//!
//! The manifest installs the release binary of Windows, never builds it: its URL and checksum
//! come from the `SHA256SUMS` of the release. Its `checkver` and `autoupdate` let Scoop's own
//! tools (`checkver.ps1 -Update`) write the manifest of a later release from the same files.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::homebrew::archive;
use crate::wasm::workspace_version;

/// The release target (binaries.yml) the manifest installs, as Scoop's `64bit` architecture.
const TARGET: &str = "x86_64-pc-windows-msvc";

const REPOSITORY: &str = "https://github.com/thkprado/jlens";

/// Prints the manifest of the workspace version, with the archive and checksum listed in `sums`
/// (a `SHA256SUMS` file), downloaded from `base`: by default the GitHub release of the version,
/// or another directory (a `file://` URL, for CI) holding the archive.
pub fn print(sums: &Path, base: Option<&str>) -> Result<()> {
    let version = workspace_version()?;
    let text = fs::read_to_string(sums).with_context(|| format!("reading {}", sums.display()))?;
    let base = base.map_or_else(
        || format!("{REPOSITORY}/releases/download/v{version}"),
        |b| b.trim_end_matches('/').to_owned(),
    );
    print!("{}", manifest(&version, &text, &base)?);
    Ok(())
}

fn manifest(version: &str, sums: &str, base: &str) -> Result<String> {
    let (sha256, file) = archive(sums, TARGET, "zip")?;
    // The archive holds one directory, named as the archive itself.
    let dir = file.trim_end_matches(".zip");
    Ok(format!(
        r###"{{
    "##": "Generated by `cargo xtask scoop` in thkprado/jlens, from the SHA256SUMS of the release. Do not edit: the Scoop workflow of thkprado/jlens replaces it when a release is published.",
    "version": "{version}",
    "description": "Evaluate, check and explain JSONata expressions",
    "homepage": "https://thkprado.github.io/jlens/",
    "license": "MIT",
    "architecture": {{
        "64bit": {{
            "url": "{base}/{file}",
            "hash": "{sha256}",
            "extract_dir": "{dir}"
        }}
    }},
    "bin": "jlens.exe",
    "checkver": {{
        "github": "{REPOSITORY}"
    }},
    "autoupdate": {{
        "architecture": {{
            "64bit": {{
                "url": "{REPOSITORY}/releases/download/v$version/jlens-$version-{TARGET}.zip",
                "extract_dir": "jlens-$version-{TARGET}"
            }}
        }},
        "hash": {{
            "url": "$baseurl/SHA256SUMS"
        }}
    }}
}}
"###
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn installs_the_windows_archive() {
        let sums = format!(
            "{}  jlens-abc-x86_64-unknown-linux-musl.tar.gz\n{}  jlens-abc-{TARGET}.zip\n",
            "0".repeat(64),
            "1".repeat(64)
        );
        let manifest = manifest("0.14.0", &sums, "file:///C:/dist").unwrap();
        assert!(manifest.contains(&format!(
            "        \"64bit\": {{\n            \
             \"url\": \"file:///C:/dist/jlens-abc-{TARGET}.zip\",\n            \
             \"hash\": \"{}\",\n            \
             \"extract_dir\": \"jlens-abc-{TARGET}\"\n        }}\n",
            "1".repeat(64)
        )));
        assert!(manifest.contains("    \"version\": \"0.14.0\",\n"));
        assert!(!manifest.contains("linux"));
        let json: serde_json::Value = serde_json::from_str(&manifest).unwrap();
        assert_eq!(json["bin"], "jlens.exe");
        assert!(archive(&sums, TARGET, "tar.gz").is_err());
    }
}
